// ─── Storage helpers ──────────────────────────────────────────────────────────
const LS_KEY = "ssp_lang";
export function getLang() {
  try { return localStorage.getItem(LS_KEY) === "gu" ? "gu" : "en"; } catch { return "en"; }
}
export function setLang(code) {
  try { localStorage.setItem(LS_KEY, code); } catch {}
}

// ─── Hook ─────────────────────────────────────────────────────────────────────
import { useCallback, useSyncExternalStore } from "react";

const subscribers = new Set();

function subscribe(listener) {
  subscribers.add(listener);
  window.addEventListener("storage", listener);
  return () => {
    subscribers.delete(listener);
    window.removeEventListener("storage", listener);
  };
}

function notifyLanguageChange() {
  subscribers.forEach((listener) => listener());
}

export function useLang() {
  const lang = useSyncExternalStore(subscribe, getLang, () => "en");

  const switchLang = useCallback((code) => {
    const next = code === "gu" ? "gu" : "en";
    setLang(next);
    document.documentElement.lang = next;
    document.documentElement.dataset.language = next;
    notifyLanguageChange();
  }, []);

  /** t(key) — simple lookup; t(key, {var: val}) — template replacement */
  const t = useCallback((key, vars) => {
    let str = (strings[lang] || strings.en)[key];
    if (str === undefined) str = strings.en[key];
    if (str === undefined) str = key; // fallback: return raw key
    if (vars && typeof str === "string") {
      Object.entries(vars).forEach(([k, v]) => {
        str = str.split(`{${k}}`).join(String(v));
      });
    }
    return str;
  }, [lang]);

  return { lang, switchLang, t, LANGUAGES };
}
